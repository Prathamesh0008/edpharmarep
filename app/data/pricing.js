// Helper function to get price for a specific product and quantity
export function getProductPricing(productSlug, quantity = 100) {
  try {
    // Get the pricing tiers for the product
    const productPricing = pricing[productSlug];
    
    if (!productPricing || !Array.isArray(productPricing)) {
      console.warn(`No pricing found for product: ${productSlug}`);
      return null;
    }

    // Find the matching price tier based on quantity
    const tier = productPricing.find(
      (t) => quantity >= t.min && quantity <= t.max
    );

    if (tier) {
      return {
        price: tier.price,
        tier: tier,
        quantity: quantity
      };
    }

    // If no tier found, return the last tier (highest quantity)
    const lastTier = productPricing[productPricing.length - 1];
    return {
      price: lastTier.price,
      tier: lastTier,
      quantity: quantity
    };
  } catch (error) {
    console.error("Error getting product pricing:", error);
    return null;
  }
}

